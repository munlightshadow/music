def set_run_font(run, name_ru="Times New Roman", size=12, bold=False, italic=False, color=None):
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.name = name_ru
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        from lxml import etree
        rFonts = etree.SubElement(rPr, qn("w:rFonts"))
    rFonts.set(qn("w:ascii"), name_ru)
    rFonts.set(qn("w:hAnsi"), name_ru)
    rFonts.set(qn("w:cs"), name_ru)
    rFonts.set(qn("w:eastAsia"), name_ru)
    if color:
        run.font.color.rgb = color


def add_title(doc, text, size=18):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(8)
    r = p.add_run(text)
    set_run_font(r, size=size, bold=True, color=RGBColor(0x1F, 0x3A, 0x5F))
    return p


